/**
 * Builds the generated `igris-anon-rpc` shim module. Only the sections a
 * repo actually needs are emitted (an ethers import in a viem-only project
 * would break its build).
 *
 * Integration API verified against anon-rpc spec v0.4.0 and
 * @anon-rpc/browser-harness@0.4.0 — see docs/ANON_RPC_NOTES.md.
 */

export const SHIM_BASENAME = 'igris-anon-rpc';

/** Nym specifier (mainnet): real anonymization, no required config. */
export const DEFAULT_SPECIFIER = '0x3aCD9742C68F6d993066Ae25533e09b9e1f60eD0';

export interface ShimNeeds {
  viem: boolean; // http(url, { fetchFn }) consumers (viem and wagmi)
  ethers: boolean; // anonJsonRpcProvider consumers
}

export function buildShim(needs: ShimNeeds, specifier = DEFAULT_SPECIFIER): string {
  const parts: string[] = [];
  parts.push(`/**
 * Generated by \`igris fix\` — routes JSON-RPC reads through Anon-RPC
 * (https://ethereum.github.io/anon-rpc/, spec v0.4.0).
 *
 * What this changes, honestly:
 *  - RPC reads no longer reveal the user's IP (or address+IP pairs) to the
 *    RPC provider; they travel through the chosen anonymizing network and
 *    exit at its router. The RPC endpoint URL itself is unchanged.
 *  - The anon-client worker is hash-pinned on-chain and sandboxed, but it
 *    sits on the RPC path like any endpoint: it could observe, censor or lie
 *    within that path. Choosing a network is a trust decision.
 *  - The ONE bootstrap read of the specifier contract goes through the
 *    user's existing EIP-1193 wallet provider and is not anonymized; it
 *    reveals only that an anon-rpc specifier is being read.
 *  - Transactions still go through the user's wallet, unchanged.
 */
import { AnonRpcWorker } from '@anon-rpc/browser-harness';

/**
 * The anonymizing network, pinned by its on-chain specifier contract.
 * Default: Nym (mainnet, ~18 MB worker bundle, a few seconds to bootstrap).
 * Alternatives (see https://ethereum.github.io/anon-rpc/adopters/):
 *   tor-js 0x700dA3193D35fA54Cd3fBf29B66f2a2A0385659e (needs config.gateways)
 *   passthrough 0x4fd77be300f31c5fe6ab266d35d27750a3478d27 (NO anonymization,
 *   integration testing only)
 */
export const ANON_RPC_SPECIFIER = '${specifier}';

type Eip1193 = { request(args: { method: string; params?: unknown[] }): Promise<unknown> };

let worker: AnonRpcWorker | undefined;

function getWorker(): AnonRpcWorker {
  if (!worker) {
    const ethereum = (globalThis as { ethereum?: Eip1193 }).ethereum;
    if (!ethereum) {
      // Fail closed: silently falling back to a direct fetch would undo the
      // privacy guarantee this module exists for.
      throw new Error(
        'igris-anon-rpc: no EIP-1193 provider found for the one-time specifier ' +
          'bootstrap read. Construct the worker yourself with preExisting.rpcProvider.',
      );
    }
    worker = new AnonRpcWorker({
      address: ANON_RPC_SPECIFIER,
      preExisting: {
        rpcProvider: { request: (args) => ethereum.request(args) },
      },
    });
  }
  return worker;
}

/**
 * Drop-in fetch routed through the sandboxed anon-client. Calls made before
 * the worker is ready are buffered by the harness, not dropped.
 */
export const igrisAnonFetch = ((input: RequestInfo | URL, init?: RequestInit) =>
  getWorker().fetch(input, init)) as typeof fetch;`);

  if (needs.ethers) {
    parts.push(`
import { FetchRequest, JsonRpcProvider } from 'ethers';
import type { Networkish } from 'ethers';

/**
 * ethers v6: a JsonRpcProvider whose HTTP layer is igrisAnonFetch, via
 * FetchRequest.getUrlFunc (the hook ethers provides for custom transports).
 */
export function anonJsonRpcProvider(
  url: string,
  network?: Networkish,
  options?: ConstructorParameters<typeof JsonRpcProvider>[2],
): JsonRpcProvider {
  const req = new FetchRequest(url);
  req.getUrlFunc = async (r, _signal) => {
    const res = await igrisAnonFetch(r.url, {
      method: r.method,
      headers: Object.fromEntries(
        [...r]
          .map(([k, v]) => [k, String(v)] as [string, string]),
      ),
      body: r.body ? new Uint8Array(r.body) : undefined,
    });
    return {
      statusCode: res.status,
      statusMessage: res.statusText,
      headers: Object.fromEntries(res.headers.entries()),
      body: new Uint8Array(await res.arrayBuffer()),
    };
  };
  return new JsonRpcProvider(req, network, options);
}`);
  }

  return parts.join('\n') + '\n';
}
